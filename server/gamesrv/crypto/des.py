def _bytes_to_bits(data: bytes) -> list[int]:
    bits = []
    for byte in data:
        for i in range(7, -1, -1):
            bits.append((byte >> i) & 1)
    return bits


def _bits_to_bytes(bits: list[int]) -> bytes:
    out = bytearray()
    for i in range(0, len(bits), 8):
        value = 0
        for bit in bits[i:i + 8]:
            value = (value << 1) | bit
        out.append(value)
    return bytes(out)


def _permute(bits: list[int], table: list[int]) -> list[int]:
    return [bits[i - 1] for i in table]


def _subkeys(key: bytes) -> list[list[int]]:
    key_bits = _permute(_bytes_to_bits(key), _PC1)
    left, right = key_bits[:28], key_bits[28:]
    keys = []
    for shift in _SHIFTS:
        left = left[shift:] + left[:shift]
        right = right[shift:] + right[:shift]
        keys.append(_permute(left + right, _PC2))
    return keys


def _feistel(right: list[int], subkey: list[int]) -> list[int]:
    expanded = _permute(right, _E)
    xored = [a ^ b for a, b in zip(expanded, subkey)]
    out = []
    for i in range(8):
        chunk = xored[i * 6:(i + 1) * 6]
        row = (chunk[0] << 1) | chunk[5]
        col = (chunk[1] << 3) | (chunk[2] << 2) | (chunk[3] << 1) | chunk[4]
        value = _SBOX[i][row * 16 + col]
        out.extend([(value >> 3) & 1, (value >> 2) & 1, (value >> 1) & 1, value & 1])
    return _permute(out, _P)


def _crypt_block(block: bytes, subkeys: list[list[int]], decrypt: bool) -> bytes:
    bits = _permute(_bytes_to_bits(block), _IP)
    left, right = bits[:32], bits[32:]
    order = list(reversed(subkeys)) if decrypt else subkeys
    for subkey in order:
        left, right = right, [a ^ b for a, b in zip(left, _feistel(right, subkey))]
    return _bits_to_bytes(_permute(right + left, _FP))


class DES:
    def __init__(self, key: bytes):
        if len(key) != 8:
            raise ValueError("DES key must be 8 bytes")
        self.key = key
        self._enc = _subkeys(key)

    def encrypt_block(self, block: bytes) -> bytes:
        return _crypt_block(block, self._enc, False)

    def decrypt_block(self, block: bytes) -> bytes:
        return _crypt_block(block, self._enc, True)

    def encrypt(self, data: bytes) -> bytes:
        return b"".join(self.encrypt_block(data[i:i + 8]) for i in range(0, len(data), 8))

    def decrypt(self, data: bytes) -> bytes:
        return b"".join(self.decrypt_block(data[i:i + 8]) for i in range(0, len(data), 8))


def bit_pad(data: bytes, block: int = 8) -> bytes:
    """客户端用的补位方式：先补一个 0x80，再补 0x00 到块边界（ISO/IEC 9797-1 method 2）。

    实测：319 字节的登录 JSON 加密后是 320 字节，末尾补位正好是 0x80。
    """
    data = data + b"\x80"
    if len(data) % block:
        data += b"\x00" * (block - len(data) % block)
    return data


def bit_unpad(data: bytes) -> bytes:
    # 去掉末尾的 0x00，再去掉一个 0x80
    end = len(data)
    while end > 0 and data[end - 1] == 0:
        end -= 1
    if end > 0 and data[end - 1] == 0x80:
        end -= 1
    return data[:end]


def des_encode(key: bytes, msg: bytes) -> bytes:
    """对应客户端的 crypt.desEncode(key, msg)。"""
    return DES(key).encrypt(bit_pad(msg))


def des_decode(key: bytes, msg: bytes) -> bytes:
    """对应客户端的 crypt.desDecode(key, msg)。"""
    if len(msg) % 8:
        return b""
    return bit_unpad(DES(key).decrypt(msg))
